"""Summarize the latest run per model into `evals/RESULTS.md`.

Usage:
    uv run python -m evals.report
"""

import json
import logging
import statistics
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from evals.run import RESULTS_DIR, TASKS

logger = logging.getLogger("evals")

REPORT_PATH = RESULTS_DIR.parent / "RESULTS.md"
HEADER = """# AI evaluation results

Generated by `uv run python -m evals.report` from the latest run per model in
`evals/results/`. Cases and scoring: `evals/cases.py` and `evals/scoring.py`. Every
answer is checked by code against the app's own guardrails and change engine; no model
grades another. Latency is measured from the developer's machine in India.

- **Pass:** the answer leads to an acceptable outcome (see each case).
- **First try:** the first answer was valid without a repair request.
- **No answer:** the model failed (timeout, outage or quota), so the app would have
  used its next model or its labelled fallback.
"""


def latest_runs(directory: Path = RESULTS_DIR) -> list[dict[str, Any]]:
    """The newest result file for each model, oldest model first."""
    runs: dict[str, dict[str, Any]] = {}
    for path in sorted(directory.glob("*.json")):
        document: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
        document["file"] = path.name
        runs[document["model"]] = document
    return list(runs.values())


def _percent(part: int, whole: int) -> str:
    return f"{part}/{whole} ({part / whole:.0%})" if whole else "-"


def _summary_row(model: str, task: str, results: Sequence[dict[str, Any]]) -> str:
    answered = [r for r in results if not r["error"]]
    latencies = sorted(r["latency_ms"] for r in answered)
    median = f"{statistics.median(latencies) / 1000:.1f} s" if latencies else "-"
    slowest = f"{latencies[-1] / 1000:.1f} s" if latencies else "-"
    passed = sum(r["passed"] for r in results)
    first_try = sum(r["first_try_valid"] for r in answered)
    errors = len(results) - len(answered)
    return (
        f"| {model} | {task} | {_percent(passed, len(results))} | "
        f"{_percent(first_try, len(answered))} | {errors} | {median} | {slowest} |"
    )


def render(runs: Sequence[dict[str, Any]]) -> str:
    """Markdown with a summary table and every failure with its reasons."""
    lines = [
        HEADER,
        "## Summary",
        "",
        "| Model | Task | Pass | First try | No answer | Median latency | Slowest |",
        "|---|---|---|---|---|---|---|",
    ]
    for run in runs:
        for task in TASKS:
            results = [r for r in run["results"] if r["task"] == task]
            if results:
                lines.append(_summary_row(run["model"], task, results))
    lines += ["", "## Failures", ""]
    for run in runs:
        failures = [r for r in run["results"] if not r["passed"]]
        lines.append(
            f"### {run['model']} ({run['run_at']}, prompts "
            f"{', '.join(run['prompt_versions'].values())})"
        )
        lines.append("")
        lines += [
            f"- `{r['task']}/{r['case_id']}`: {'; '.join(r['reasons'])}" for r in failures
        ] or ["- None."]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main() -> int:
    """Write the report."""
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    runs = latest_runs()
    REPORT_PATH.write_text(render(runs), encoding="utf-8")
    logger.info("wrote %s from %d run(s)", REPORT_PATH.name, len(runs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
