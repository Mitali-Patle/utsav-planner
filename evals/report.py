"""Summarize the latest run per model into `evals/RESULTS.md`.

Usage:
    uv run python -m evals.report
"""

import json
import logging
import statistics
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from evals.run import PROMPT_OF, RESULTS_DIR, TASKS

logger = logging.getLogger("evals")

REPORT_PATH = RESULTS_DIR.parent / "RESULTS.md"
MAX_NO_ANSWER_SHARE = 0.2
HEADER = """# AI evaluation results

Generated by `uv run python -m evals.report` from `evals/results/`: for each model and task,
the latest run in which at most 20% of the cases got no answer (a run with more measured an
outage, not the model; it still appears in the run history). Cases and scoring:
`evals/cases.py` and `evals/scoring.py`. Every answer is checked by code against the app's
own guardrails and change engine; no model grades another. Latency is measured from the
developer's machine in India.

- **Pass:** answers that lead to an acceptable outcome, out of the cases the model
  answered. Cases with no answer are counted separately, so an outage or a spent quota
  never looks like a wrong answer.
- **First try:** the first answer was valid without a repair request.
- **No answer:** the model failed (timeout, outage or quota), so the app would have
  used its next model or its labelled fallback.
"""


def all_runs(directory: Path = RESULTS_DIR) -> list[dict[str, Any]]:
    """Every saved run, oldest first."""
    runs = []
    for path in sorted(directory.glob("*.json")):
        document: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
        document["file"] = path.name
        runs.append(document)
    return runs


@dataclass(frozen=True)
class Measurement:
    """The results of one task in one run."""

    model: str
    task: str
    run_at: str
    prompt_version: str
    results: list[dict[str, Any]]


def best_measurements(runs: Sequence[dict[str, Any]]) -> list[Measurement]:
    """For each model and task, the latest run in which that task was mostly answered.

    A run where more than `MAX_NO_ANSWER_SHARE` of a task's cases got no answer measured an
    outage, not the model; it is used only if no better run exists. Runs stay in the history.
    """
    chosen: dict[tuple[str, str], Measurement] = {}
    for run in runs:
        for task in TASKS:
            results = [r for r in run["results"] if r["task"] == task]
            if not results:
                continue
            key = (run["model"], task)
            candidate = Measurement(
                run["model"], task, run["run_at"], run["prompt_versions"][PROMPT_OF[task]], results
            )
            if _usable(candidate) or key not in chosen or not _usable(chosen[key]):
                chosen[key] = candidate
    return list(chosen.values())


def _usable(measurement: Measurement) -> bool:
    errors = sum(bool(r["error"]) for r in measurement.results)
    return errors <= MAX_NO_ANSWER_SHARE * len(measurement.results)


def _history_row(run: dict[str, Any]) -> str:
    cells = []
    for task in TASKS:
        answered = [r for r in run["results"] if r["task"] == task and not r["error"]]
        cells.append(f"{sum(r['passed'] for r in answered)}/{len(answered)}")
    errors = sum(r["error"] for r in run["results"])
    versions = ", ".join(v.rsplit("-", 1)[-1] for v in run["prompt_versions"].values())
    return (
        f"| {run['run_at'][:16]} | {run['model']} | {versions} | {' | '.join(cells)} | {errors} |"
    )


def _percent(part: int, whole: int) -> str:
    return f"{part}/{whole} ({part / whole:.0%})" if whole else "-"


def _summary_row(measurement: Measurement) -> str:
    results = measurement.results
    answered = [r for r in results if not r["error"]]
    latencies = sorted(r["latency_ms"] for r in answered)
    median = f"{statistics.median(latencies) / 1000:.1f} s" if latencies else "-"
    slowest = f"{latencies[-1] / 1000:.1f} s" if latencies else "-"
    passed = sum(r["passed"] for r in results)
    first_try = sum(r["first_try_valid"] for r in answered)
    errors = len(results) - len(answered)
    return (
        f"| {measurement.model} | {measurement.task} | {measurement.run_at[:16]} | "
        f"{measurement.prompt_version} | {_percent(passed, len(answered))} | "
        f"{_percent(first_try, len(answered))} | {errors} | {median} | {slowest} |"
    )


def render(measurements: Sequence[Measurement], history: Sequence[dict[str, Any]] = ()) -> str:
    """Markdown with a summary table, every failure with its reasons, and the run history."""
    lines = [
        HEADER,
        "## Summary",
        "",
        "| Model | Task | Run (UTC) | Prompt | Pass | First try | No answer | Median latency "
        "| Slowest |",
        "|---|---|---|---|---|---|---|---|---|",
        *(_summary_row(m) for m in measurements),
        "",
        "## Failures",
        "",
    ]
    for m in measurements:
        failures = [r for r in m.results if not r["passed"] and not r["error"]]
        lines += [f"### {m.model}, {m.task} ({m.prompt_version})", ""]
        lines += [f"- `{r['case_id']}`: {'; '.join(r['reasons'])}" for r in failures] or ["- None."]
        lines.append("")
    if history:
        lines += [
            "## Run history",
            "",
            "Passed out of answered. Prompt versions are personalize, interpret_change and",
            "alternatives, in that order.",
            "",
            "| Run (UTC) | Model | Prompts | Change | Personalize | Alternatives | No answer |",
            "|---|---|---|---|---|---|---|",
            *(_history_row(run) for run in history),
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


def main() -> int:
    """Write the report."""
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    runs = all_runs()
    REPORT_PATH.write_text(render(best_measurements(runs), runs), encoding="utf-8")
    logger.info("wrote %s from %d run(s)", REPORT_PATH.name, len(runs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
